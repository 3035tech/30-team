/**
 * Validate panel.help.* has Title+Body for every canonical section (both locales).
 * @returns {{ ok: true } | { ok: false, missing: string[] }}
 */
export function validateHelpGuideCoverage(locales = ['pt-BR', 'en']) {
  const missing = [];
  for (const loc of locales) {
    const pack = messages[normalizeLocale(loc)]?.panel?.help || {};
    for (const section of HELP_GUIDE_SECTIONS) {
      if (!pack[`${section}Title`] || !pack[`${section}Body`]) {
        missing.push(`${loc}:${section}`);
      }
    }
  }
  if (missing.length) return { ok: false, missing };
  return { ok: true };
}
