/**
 * @param {string|null|undefined} code
 * @param {number} [fallback=400]
 * @returns {number}
 */
export function httpStatusForError(code, fallback = 400) {
  if (code == null || code === '') return fallback;
  const status = HTTP_BY_CODE[String(code)];
  return Number.isFinite(status) ? status : fallback;
}
